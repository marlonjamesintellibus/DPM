// Runs every model setting from section 11 of ../tla-plus-and-tlc.md,
// compares the outcome with what was expected, and writes results.md.
//
//   node run-all.mjs            summary plus the traces for every failure
//   node run-all.mjs --quiet    summary only
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { check, formatTrace } from './checker.mjs';
import { ROWS, PLANTS } from './checks.mjs';


const quiet = process.argv.includes('--quiet');
const summary = [];
const details = [];

for (const row of [...ROWS, ...PLANTS]) {
  const t0 = performance.now();
  const r = check(row.model);
  const ms = Math.round(performance.now() - t0);
  const failed = Object.keys(r.failures);
  const asExpected =
    failed.length === row.expectFail.length && row.expectFail.every((n) => failed.includes(n));
  summary.push({
    spec: row.spec,
    setting: row.setting,
    states: r.states,
    expected: row.expectFail.length ? `${row.expectFail.join(', ')} fails` : 'all pass',
    actual: failed.length ? `${failed.join(', ')} fails` : `all ${r.checked.length} pass`,
    match: asExpected ? 'yes' : 'NO',
    ms,
  });
  for (const [prop, f] of Object.entries(r.failures)) {
    let text = `### ${row.spec}, ${row.setting}: ${prop} fails (${f.kind}${f.instance ? `, for ${f.instance}` : ''})\n\n`;
    text += '```\n' + formatTrace(f.trace, '') + '\n';
    if (typeof f.loop === 'string') text += `then: ${f.loop}\n`;
    else if (f.loop) text += `then loops forever (${f.loopStates} states never reach the goal):\n${formatTrace(f.loop, '  ')}\n`;
    text += '```\n';
    details.push(text);
  }
}

const table = [
  '| Spec | Setting | States | Expected | Actual | Match |',
  '|---|---|---|---|---|---|',
  ...summary.map((s) => `| ${s.spec} | ${s.setting} | ${s.states.toLocaleString('en-US')} | ${s.expected} | ${s.actual} | ${s.match} |`),
].join('\n');

console.log(table);
if (!quiet) console.log('\n' + details.join('\n'));

const out = [
  '# DPM model check results',
  '',
  `Generated by \`node run-all.mjs\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`,
  '',
  table,
  '',
  '## Counterexample traces',
  '',
  'Each trace starts from an initial state. Step 1 shows the whole state; later steps show only what changed.',
  '',
  ...details,
].join('\n');
writeFileSync(fileURLToPath(new URL('./results.md', import.meta.url)), out);

const mismatches = summary.filter((s) => s.match !== 'yes').length;
console.log(mismatches ? `\n${mismatches} row(s) did not match expectations.` : '\nAll rows matched expectations.');
process.exit(mismatches ? 1 : 0);
